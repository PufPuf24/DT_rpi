# Peak detection
# ---------------------------------------------------------------------------


def find_extremum(
    x: np.ndarray,
    y: np.ndarray,
    window: tuple[float, float],
    *,
    kind: str,
    prominence: float,
) -> tuple[float, float]:
    """Locate one peak (``kind='max'``) or valley (``kind='min'``) inside a window.

    Mirrors the MATLAB pattern ``findpeaks(Y,'MinPeakProminence',p)`` followed by
    picking the most extreme candidate. Returns ``(nan, nan)`` when nothing in
    the window clears the prominence threshold -- which is how the original code
    marks a peak that ageing has flattened past recognition.
    """
    if kind not in {"max", "min"}:
        raise ValueError(f"kind must be 'max' or 'min', got {kind!r}")

    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    mask = (x >= window[0]) & (x <= window[1]) & np.isfinite(y)
    if not mask.any():
        return np.nan, np.nan

    xs, ys = x[mask], y[mask]
    signal = ys if kind == "max" else -ys

    locs, _ = find_peaks(signal, prominence=prominence)
    if locs.size == 0:
        return np.nan, np.nan

    best = locs[np.argmax(signal[locs])]
    return float(xs[best]), float(ys[best])


def find_extremum_or_global(
    x: np.ndarray,
    y: np.ndarray,
    window: tuple[float, float],
    *,
    kind: str,
    prominence: float,
) -> tuple[float, float]:
    """As :func:`find_extremum`, but falls back to the window's global extremum.

    The DVA extraction uses this fallback so a feature is always produced, even
    once the local peak has degenerated into a shoulder.
    """
    xx, yy = find_extremum(x, y, window, kind=kind, prominence=prominence)
    if np.isfinite(xx):
        return xx, yy

    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    mask = (x >= window[0]) & (x <= window[1]) & np.isfinite(y)
    if not mask.any():
        return np.nan, np.nan

    xs, ys = x[mask], y[mask]
    idx = int(np.argmax(ys) if kind == "max" else np.argmin(ys))
    return float(xs[idx]), float(ys[idx])


def find_knee(
    x: np.ndarray,
    y: np.ndarray,
    window: tuple[float, float],
) -> tuple[float, float]:
    """Flattest point in a window -- MATLAB's ``[~,i] = min(abs(diff(Y)))``.

    Used for the aged-cell DVA charge Peak B, where the peak has degenerated
    into a shoulder and a prominence-based search no longer finds anything.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    mask = (x >= window[0]) & (x <= window[1]) & np.isfinite(y)
    if mask.sum() < 2:
        return np.nan, np.nan

    xs, ys = x[mask], y[mask]
    idx = int(np.argmin(np.abs(np.diff(ys))))
    return float(xs[idx]), float(ys[idx])
